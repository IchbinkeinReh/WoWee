cast_check::Spell checkSpell(const Row& r) {
    cast_check::Spell s;
    s.attr = r.attr[0];
    s.attrEx = r.attr[1];
    s.attrEx2 = r.attr[2];
    s.attrEx3 = r.attr[3];
    s.attrEx4 = r.attr[4];
    s.attrEx5 = r.attr[5];
    s.attrEx6 = r.attr[6];
    s.attrEx7 = r.attr[7];
    s.schoolMask = r.schoolMask;
    for (int w = 0; w < 2; ++w) {
        s.stances[w] = r.stances[w];
        s.stancesNot[w] = r.stancesNot[w];
    }
    s.targets = r.targets;
    s.casterAuraState = r.casterAuraState;
    s.casterAuraStateNot = r.casterAuraStateNot;
    s.casterAuraSpell = r.casterAuraSpell;
    s.excludeCasterAuraSpell = r.excludeCasterAuraSpell;
    s.recoveryTime = r.recovery;
    s.categoryRecoveryTime = r.categoryRecovery;
    s.interruptFlags = r.interruptFlags;
    s.auraInterruptFlags = r.auraInterruptFlags;
    s.channelInterruptFlags = r.channelInterruptFlags;
    for (int k = 0; k < 3; ++k) {
        s.effect[k] = r.effect[k];
        s.effectMechanic[k] = r.effectMechanic[k];
        s.implicitA[k] = r.implicitA[k];
        s.implicitB[k] = r.implicitB[k];
        s.aura[k] = r.aura[k];
        s.misc[k] = r.misc[k];
        s.trigger[k] = r.trigger[k];
    }
    s.preventionType = r.preventionType;
    return s;
}

/// SpellShapeshiftForm.dbc's Flags for the forms the rows are cast in.
uint32_t formFlags(int form) {
    switch (form) {
        case 1: return 0x2f8;  // cat
        case 5: return 0x2d8;  // bear
        case 17: return 0x7;   // battle stance
        default: return 0;
    }
}

uint8_t checkAt(const Row& r, int state) {
    cast_check::Caster c;
    c.mapType = 0;
    c.sheath = 1;
    c.daytime = 1;
    c.unitFlags = state == 1 ? 0x80000u : 0u;  // UNIT_FLAG_IN_COMBAT
    c.moveFlags = state == 2 ? 0x1u : 0u;      // MOVEMENTFLAG_FORWARD
    c.outdoors = state == 3 ? 0 : 1;
    c.form = static_cast<uint8_t>(r.form);
    c.formRow = r.form != 0;
    c.formFlags = formFlags(r.form);
    c.wouldStand = c.wouldUnshift = c.wouldDismount = true;
    // 0x007ff180: Attributes 0x2 adds half a second to any.
    c.hasCastTime = r.castTime != 0 || (r.attr[0] & 0x2u) != 0;
    return cast_check::check(checkSpell(r), c).code;
}

Out unitFor(const Row& r, int asked) {
    const uint32_t required = ground_target::requiredTargets(r.targets, r.implicitA[0], false);
    if (ground_target::wantsLocation(required)) return Ground;
    if ((required & 0x10u) != 0) return Item;
    constexpr uint64_t kPlayer = 1, kHostile = 2, kFriend = 3;
    const unit_target::Spell us{r.attr[1], r.attr[2], r.attr[3], r.attr[5], r.attr[6], r.targetCreatureType};
    const auto take = [&](uint64_t guid) {
        unit_target::Unit u;
        unit_target::Relations rel;
        u.health = 100;
        if (guid == kHostile) {
            u.type = unit_target::kTypeUnit;
            u.creatureType = 7;  // humanoid
            rel.mayAttack = true;
        } else {
            u.type = unit_target::kTypeUnit | unit_target::kTypePlayer;
            u.unitFlags = unit_target::kFlagPlayerControlled;
            u.isCaster = guid == kPlayer;
            rel.inParty = rel.inRaid = rel.mayAssist = rel.mayAssistEx6 = true;
        }
        const auto t = unit_target::takeUnit(us, u, rel, required);
        struct {
            bool taken;
            uint32_t required;
            uint64_t unit;
        } o{t.taken, t.required, guid};
        return o;
    };
    const uint64_t unit = asked == 0 ? 0 : asked == 1 ? kHostile : kFriend;
    const auto chosen = unit_target::chooseUnit(required, ground_target::takesNoUnit(r.implicitA[0]), unit, false,
                                                true, unit != kFriend, kPlayer, kPlayer, take);
    switch (chosen.what) {
        case unit_target::Choice::AtNone: return AtNone;
        case unit_target::Choice::AtUnit:
            return chosen.unit == kPlayer ? Self : chosen.unit == kHostile ? Hostile : Friend;
        case unit_target::Choice::Partly: break;
        case unit_target::Choice::NoUnit:
            switch (unit_target::noUnitFailure(r.attr[0], r.attr[5], required, true, true, unit != 0)) {
                case unit_target::kFailedBadTargets: return BadTargets;
                case unit_target::kFailedNoTarget: return NoTarget;
                case 0: return Cursor;
                default: break;
            }
            break;
    }
    FAIL("unexpected choice for " << r.name);
    return Cursor;
}

